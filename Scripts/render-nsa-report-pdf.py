def discover_node() -> Path:
    configured = os.environ.get("HEVEA_NODE_PATH")
    if configured:
        return Path(configured)
    if RUNTIME_NODE.is_file():
        return RUNTIME_NODE
    return Path("node")


def render_pdf(html_path: Path, output_path: Path) -> dict[str, int]:
    environment = os.environ.copy()
    configured_modules = environment.get("NODE_PATH")
    if configured_modules is None and RUNTIME_NODE_MODULES.is_dir():
        environment["NODE_PATH"] = str(RUNTIME_NODE_MODULES)
    printer = REPOSITORY_ROOT / "Scripts/print-html-pdf.mjs"
    completed = subprocess.run(
        [str(discover_node()), str(printer), str(html_path), str(output_path)],
        cwd=REPOSITORY_ROOT,
        env=environment,
        check=True,
        capture_output=True,
        text=True,
    )
    line = completed.stdout.strip().splitlines()[-1]
    receipt = json.loads(line)
    return {str(key): int(value) for key, value in receipt.items()}


def main() -> int:
    arguments = parse_arguments()
    source_path = arguments.source.resolve()
    output_path = arguments.output.resolve()
    if not source_path.is_file():
        raise FileNotFoundError(source_path)

    source = source_path.read_text(encoding="utf-8")
    body = decorate_claims(markdown_to_body(source))
    title, body = extract_title(body)
    rendered = document_html(title, body, source_path.name)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    html_path = output_path.with_suffix(".html")
    html_path.write_text(rendered, encoding="utf-8")
    try:
        receipt = render_pdf(html_path, output_path)
    finally:
        if not arguments.keep_html and html_path.exists():
            html_path.unlink()

    if not output_path.is_file() or output_path.stat().st_size < 100_000:
        raise RuntimeError("PDF output is missing or unexpectedly small")
    print(
        json.dumps(
            {
                "output": str(output_path),
                "bytes": output_path.stat().st_size,
                **receipt,
            },
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
