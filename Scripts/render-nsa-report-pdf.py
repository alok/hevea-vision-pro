def markdown_to_body(source: str) -> str:
    return markdown.markdown(
        source,
        extensions=[
            "fenced_code",
            "sane_lists",
            "tables",
            "toc",
            "pymdownx.arithmatex",
        ],
        extension_configs={
            "pymdownx.arithmatex": {
                "generic": True,
                "block_tag": "div",
            }
        },
        output_format="html5",
    )


def extract_title(body: str) -> tuple[str, str]:
    pattern = re.compile(r'<h1(?: id="[^"]+")?>(.*?)</h1>', re.DOTALL)
    match = pattern.search(body)
    if match is None:
        return "A sphere inside a point", body
    title = re.sub(r"<[^>]+>", "", match.group(1))
    return html.unescape(title), body[: match.start()] + body[match.end() :]


def decorate_claims(body: str) -> str:
    for label, class_name in (
        ("PAPER", "paper"),
        ("NSA-EQUIV", "nsa"),
        ("NEW-COROLLARY", "new"),
        ("APP-MODEL", "app"),
        ("OPEN", "open"),
    ):
        body = body.replace(
            f"[{label}]",
            f'<span class="claim claim-{class_name}">{label}</span>',
        )
    return body


